-- Finance OS - initial schema + Row Level Security for Supabase Postgres.
-- Version: 0001
--
-- How to apply:
--   Supabase Dashboard -> SQL Editor -> paste and run, or
--   psql "$SUPABASE_DB_URL" -f supabase/migrations/0001_finance_os_init.sql
--
-- Non-destructive: uses CREATE TABLE IF NOT EXISTS and CREATE INDEX IF NOT EXISTS.
-- The Express backend connects as the table owner (via SUPABASE_DB_URL/DATABASE_URL)
-- and therefore bypasses RLS. The Data API roles (anon/authenticated) are denied by
-- default, so the publishable key cannot read or write any private data.

CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  first_name TEXT NOT NULL,
  last_name TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  country TEXT DEFAULT 'MZ',
  currency TEXT DEFAULT 'MZN',
  language TEXT DEFAULT 'en',
  theme TEXT DEFAULT 'light',
  onboarding_completed INTEGER DEFAULT 0,
  onboarding_step INTEGER DEFAULT 0,
  emergency_fund_target DOUBLE PRECISION DEFAULT 0,
  min_liquidity DOUBLE PRECISION DEFAULT 0,
  created_at TEXT DEFAULT to_char(timezone('utc', now()), 'YYYY-MM-DD HH24:MI:SS'),
  updated_at TEXT DEFAULT to_char(timezone('utc', now()), 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE IF NOT EXISTS password_resets (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  token TEXT NOT NULL,
  expires_at TEXT NOT NULL,
  used INTEGER DEFAULT 0
);

CREATE TABLE IF NOT EXISTS accounts (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  type TEXT NOT NULL,
  provider TEXT DEFAULT '',
  currency TEXT DEFAULT 'MZN',
  initial_balance DOUBLE PRECISION NOT NULL DEFAULT 0,
  icon TEXT DEFAULT 'wallet',
  color TEXT DEFAULT '#2E90FA',
  notes TEXT DEFAULT '',
  status TEXT DEFAULT 'active',
  business_id INTEGER,
  client_id TEXT,
  created_at TEXT DEFAULT to_char(timezone('utc', now()), 'YYYY-MM-DD HH24:MI:SS'),
  updated_at TEXT DEFAULT to_char(timezone('utc', now()), 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE IF NOT EXISTS businesses (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  logo TEXT DEFAULT '',
  description TEXT DEFAULT '',
  type TEXT DEFAULT 'other',
  brand_color TEXT DEFAULT '#7A5AF8',
  currency TEXT DEFAULT 'MZN',
  status TEXT DEFAULT 'active',
  notes TEXT DEFAULT '',
  client_id TEXT,
  created_at TEXT DEFAULT to_char(timezone('utc', now()), 'YYYY-MM-DD HH24:MI:SS'),
  updated_at TEXT DEFAULT to_char(timezone('utc', now()), 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE IF NOT EXISTS categories (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  icon TEXT DEFAULT 'tag',
  color TEXT DEFAULT '#2E90FA',
  type TEXT NOT NULL,
  scope TEXT DEFAULT 'personal',
  business_id INTEGER,
  parent_id INTEGER,
  status TEXT DEFAULT 'active',
  created_at TEXT DEFAULT to_char(timezone('utc', now()), 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE IF NOT EXISTS transactions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  amount DOUBLE PRECISION NOT NULL,
  date TEXT NOT NULL,
  type TEXT NOT NULL,
  account_id INTEGER,
  to_account_id INTEGER,
  category_id INTEGER,
  business_id INTEGER,
  debt_id INTEGER,
  goal_id INTEGER,
  description TEXT DEFAULT '',
  notes TEXT DEFAULT '',
  tags TEXT DEFAULT '',
  attachment TEXT DEFAULT '',
  recurring_id INTEGER,
  voided_at TEXT,
  void_reason TEXT DEFAULT '',
  client_id TEXT,
  created_at TEXT DEFAULT to_char(timezone('utc', now()), 'YYYY-MM-DD HH24:MI:SS'),
  updated_at TEXT DEFAULT to_char(timezone('utc', now()), 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE IF NOT EXISTS budgets (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  scope TEXT DEFAULT 'overall',
  business_id INTEGER,
  category_id INTEGER,
  amount DOUBLE PRECISION NOT NULL,
  period TEXT DEFAULT 'monthly',
  start_date TEXT,
  end_date TEXT,
  status TEXT DEFAULT 'active',
  client_id TEXT,
  created_at TEXT DEFAULT to_char(timezone('utc', now()), 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE IF NOT EXISTS debts (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  creditor TEXT NOT NULL,
  original_amount DOUBLE PRECISION NOT NULL,
  current_balance DOUBLE PRECISION NOT NULL,
  opening_balance DOUBLE PRECISION,
  interest DOUBLE PRECISION DEFAULT 0,
  due_date TEXT,
  minimum_payment DOUBLE PRECISION DEFAULT 0,
  priority TEXT DEFAULT 'medium',
  notes TEXT DEFAULT '',
  status TEXT DEFAULT 'active',
  account_id INTEGER,
  client_id TEXT,
  created_at TEXT DEFAULT to_char(timezone('utc', now()), 'YYYY-MM-DD HH24:MI:SS'),
  updated_at TEXT DEFAULT to_char(timezone('utc', now()), 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE IF NOT EXISTS goals (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  target_amount DOUBLE PRECISION NOT NULL,
  current_amount DOUBLE PRECISION DEFAULT 0,
  target_date TEXT,
  priority TEXT DEFAULT 'medium',
  account_id INTEGER,
  notes TEXT DEFAULT '',
  status TEXT DEFAULT 'active',
  client_id TEXT,
  created_at TEXT DEFAULT to_char(timezone('utc', now()), 'YYYY-MM-DD HH24:MI:SS'),
  updated_at TEXT DEFAULT to_char(timezone('utc', now()), 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE IF NOT EXISTS recurring_transactions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  amount DOUBLE PRECISION NOT NULL,
  frequency TEXT NOT NULL,
  start_date TEXT NOT NULL,
  end_date TEXT,
  next_date TEXT NOT NULL,
  account_id INTEGER,
  to_account_id INTEGER,
  category_id INTEGER,
  business_id INTEGER,
  debt_id INTEGER,
  type TEXT NOT NULL,
  description TEXT DEFAULT '',
  status TEXT DEFAULT 'active',
  created_at TEXT DEFAULT to_char(timezone('utc', now()), 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE IF NOT EXISTS attachments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  transaction_id INTEGER,
  filename TEXT NOT NULL,
  path TEXT NOT NULL,
  mime TEXT DEFAULT '',
  created_at TEXT DEFAULT to_char(timezone('utc', now()), 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE IF NOT EXISTS financial_snapshots (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  date TEXT NOT NULL,
  net_worth DOUBLE PRECISION NOT NULL,
  assets DOUBLE PRECISION NOT NULL,
  liabilities DOUBLE PRECISION NOT NULL,
  cash DOUBLE PRECISION NOT NULL,
  debt DOUBLE PRECISION NOT NULL,
  UNIQUE(user_id, date)
);

CREATE TABLE IF NOT EXISTS notifications (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  type TEXT DEFAULT 'info',
  title TEXT NOT NULL,
  message TEXT NOT NULL,
  read INTEGER DEFAULT 0,
  created_at TEXT DEFAULT to_char(timezone('utc', now()), 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE IF NOT EXISTS allocation_rules (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  trigger_type TEXT DEFAULT 'income',
  source TEXT DEFAULT '',
  splits TEXT NOT NULL DEFAULT '[]',
  enabled INTEGER DEFAULT 1,
  created_at TEXT DEFAULT to_char(timezone('utc', now()), 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE IF NOT EXISTS audit_log (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER,
  action TEXT NOT NULL,
  entity TEXT NOT NULL,
  entity_id INTEGER,
  before_json TEXT DEFAULT '',
  after_json TEXT DEFAULT '',
  created_at TEXT DEFAULT to_char(timezone('utc', now()), 'YYYY-MM-DD HH24:MI:SS')
);

CREATE TABLE IF NOT EXISTS idempotency_keys (
  user_id INTEGER NOT NULL,
  key TEXT NOT NULL,
  method TEXT NOT NULL,
  path TEXT NOT NULL,
  entity TEXT,
  entity_id INTEGER,
  created_at TEXT DEFAULT to_char(timezone('utc', now()), 'YYYY-MM-DD HH24:MI:SS'),
  PRIMARY KEY (user_id, key)
);

CREATE INDEX IF NOT EXISTS idx_accounts_user ON accounts(user_id);
CREATE INDEX IF NOT EXISTS idx_businesses_user ON businesses(user_id);
CREATE INDEX IF NOT EXISTS idx_categories_user ON categories(user_id);
CREATE INDEX IF NOT EXISTS idx_tx_user_date ON transactions(user_id, date);
CREATE INDEX IF NOT EXISTS idx_tx_account ON transactions(user_id, account_id);
CREATE INDEX IF NOT EXISTS idx_tx_to_account ON transactions(user_id, to_account_id);
CREATE INDEX IF NOT EXISTS idx_tx_business ON transactions(user_id, business_id);
CREATE INDEX IF NOT EXISTS idx_tx_debt ON transactions(user_id, debt_id);
CREATE INDEX IF NOT EXISTS idx_debts_user ON debts(user_id);
CREATE INDEX IF NOT EXISTS idx_goals_user ON goals(user_id);
CREATE INDEX IF NOT EXISTS idx_budgets_user ON budgets(user_id);
CREATE INDEX IF NOT EXISTS idx_snapshots_user_date ON financial_snapshots(user_id, date);
CREATE INDEX IF NOT EXISTS idx_attachments_user ON attachments(user_id);
CREATE INDEX IF NOT EXISTS idx_audit_user ON audit_log(user_id, created_at);

CREATE UNIQUE INDEX IF NOT EXISTS idx_tx_client ON transactions(user_id, client_id) WHERE client_id IS NOT NULL AND client_id != '';
CREATE UNIQUE INDEX IF NOT EXISTS idx_acc_client ON accounts(user_id, client_id) WHERE client_id IS NOT NULL AND client_id != '';
CREATE UNIQUE INDEX IF NOT EXISTS idx_biz_client ON businesses(user_id, client_id) WHERE client_id IS NOT NULL AND client_id != '';
CREATE UNIQUE INDEX IF NOT EXISTS idx_debt_client ON debts(user_id, client_id) WHERE client_id IS NOT NULL AND client_id != '';
CREATE UNIQUE INDEX IF NOT EXISTS idx_goal_client ON goals(user_id, client_id) WHERE client_id IS NOT NULL AND client_id != '';
CREATE UNIQUE INDEX IF NOT EXISTS idx_budget_client ON budgets(user_id, client_id) WHERE client_id IS NOT NULL AND client_id != '';

-- Row Level Security: enable on every table and deny Data API roles by default.
-- The Express backend is the table owner and bypasses RLS, enforcing user_id scoping in code.
ALTER TABLE users ENABLE ROW LEVEL SECURITY;
ALTER TABLE password_resets ENABLE ROW LEVEL SECURITY;
ALTER TABLE accounts ENABLE ROW LEVEL SECURITY;
ALTER TABLE businesses ENABLE ROW LEVEL SECURITY;
ALTER TABLE categories ENABLE ROW LEVEL SECURITY;
ALTER TABLE transactions ENABLE ROW LEVEL SECURITY;
ALTER TABLE budgets ENABLE ROW LEVEL SECURITY;
ALTER TABLE debts ENABLE ROW LEVEL SECURITY;
ALTER TABLE goals ENABLE ROW LEVEL SECURITY;
ALTER TABLE recurring_transactions ENABLE ROW LEVEL SECURITY;
ALTER TABLE attachments ENABLE ROW LEVEL SECURITY;
ALTER TABLE financial_snapshots ENABLE ROW LEVEL SECURITY;
ALTER TABLE notifications ENABLE ROW LEVEL SECURITY;
ALTER TABLE allocation_rules ENABLE ROW LEVEL SECURITY;
ALTER TABLE audit_log ENABLE ROW LEVEL SECURITY;
ALTER TABLE idempotency_keys ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON ALL TABLES IN SCHEMA public FROM anon, authenticated;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM anon, authenticated;
ALTER DEFAULT PRIVILEGES IN SCHEMA public REVOKE ALL ON TABLES FROM anon, authenticated;
ALTER DEFAULT PRIVILEGES IN SCHEMA public REVOKE ALL ON SEQUENCES FROM anon, authenticated;

